from .models import AgentRole, Authority, Ministry


def _standard_roles(domain: str) -> tuple[AgentRole, ...]:
    return (
        AgentRole(
            role_id=f"{domain}.lead",
            title="Lead",
            purpose="Own the ministry mandate, mission framing and final synthesis.",
            skills=("mission_framing", "synthesis"),
        ),
        AgentRole(
            role_id=f"{domain}.researcher",
            title="Researcher",
            purpose="Gather evidence, models, sources and candidate explanations.",
            skills=("research", "evidence_register"),
        ),
        AgentRole(
            role_id=f"{domain}.analyst",
            title="Analyst",
            purpose="Formalize variables, compare scenarios and quantify uncertainty.",
            skills=("analysis", "uncertainty"),
        ),
        AgentRole(
            role_id=f"{domain}.critic",
            title="Critic",
            purpose="Seek contradictions, failure modes and disconfirming evidence.",
            skills=("contradiction_audit", "red_team"),
        ),
        AgentRole(
            role_id=f"{domain}.integrator",
            title="Integrator",
            purpose="Translate outputs for other ministries and preserve context.",
            skills=("context_capsule_builder", "translation"),
        ),
    )


